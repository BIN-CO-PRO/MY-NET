const ORDER: SocialKey[] = ["linkedin", "x", "instagram", "tiktok", "threads", "orcid"];

export function SocialIcons({
  links,
  size = 18,
  className = "",
}: {
  links?: Record<string, string> | null;
  size?: number;
  className?: string;
}) {
  const resolved = links ?? {};
  const items = ORDER.filter((k) => resolved[k]).map((k) => ({ key: k, href: resolved[k]! }));

  if (items.length === 0) return null;

  return (
    <div className={`flex items-center gap-2 ${className}`}>
      {items.map(({ key, href }) => {
        const meta = ICONS[key];
        const isExternal = href.startsWith("http");
        const Comp = isExternal ? "a" : Link;
        const props = isExternal
          ? { href, target: "_blank", rel: "noopener noreferrer" }
          : { to: href };
        return (
          <Comp
            key={key}
            {...(props as any)}
            aria-label={meta.label}
            className="inline-flex h-9 w-9 items-center justify-center rounded-full border border-border bg-card/60 text-muted-foreground transition-all hover:text-primary hover:border-primary/40 hover:-translate-y-0.5"
          >
            <svg width={size} height={size} viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
              <path d={meta.path} />
            </svg>
          </Comp>
        );
      })}
    </div>
  );
}
